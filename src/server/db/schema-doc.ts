/**
 * Builds `docs/SCHEMA.md` from the Drizzle schema, so the reference can never drift from the code.
 * Regenerate with `pnpm exec tsx scripts/schema-doc.ts`; a unit test fails if the file is stale.
 */

const FILES: { file: string; title: string; module: Record<string, unknown> }[] = [
  { file: "identity.ts", title: "Identity and consent", module: identity },
  { file: "content.ts", title: "Content", module: content },
  { file: "tools-radar.ts", title: "Tools, Radar and course generation", module: toolsRadar },
  { file: "learning.ts", title: "Learning", module: learning },
  { file: "ai.ts", title: "AI and credits", module: ai },
  { file: "safety.ts", title: "Safety", module: safety },
  { file: "billing-cms.ts", title: "Billing and CMS", module: billingCms },
  { file: "system.ts", title: "System", module: system },
];

const APPEND_ONLY = new Set(["consent_record", "credit_ledger", "audit_log"]);
const BETTER_AUTH = new Set(["user", "session", "account", "verification", "two_factor", "auth_rate_limit"]);

const camel = (snake: string) => snake.replace(/_([a-z0-9])/g, (_m, c: string) => c.toUpperCase());

function describeTable(exportName: string, table: PgTable): string {
  const config = getTableConfig(table);
  const references = new Map<string, string>();
  for (const fk of config.foreignKeys) {
    const ref = fk.reference();
    const column = ref.columns[0]?.name;
    const target = ref.foreignColumns[0];
    if (!column || !target) continue;
    const targetTable = getTableName(ref.foreignTable);
    const suffix = target.name === "id" ? "" : `.${target.name}`;
    const onDelete = fk.onDelete && fk.onDelete !== "no action" ? ` ${fk.onDelete}` : "";
    references.set(column, `→${targetTable}${suffix}${onDelete}`);
  }

  const columns = config.columns.map((column) => {
    const parts = [column.name, column.getSQLType().replace("timestamp with time zone", "timestamptz")];
    if (column.primary) parts.push("pk");
    if (!column.notNull && !column.primary) parts[1] = `${parts[1]}?`;
    const reference = references.get(column.name);
    if (reference) parts.push(reference);
    return parts.join(" ");
  });

  const notes: string[] = [];
  if (exportName !== camel(config.name)) notes.push(`export \`${exportName}\``);
  if (BETTER_AUTH.has(config.name)) notes.push("Better Auth");
  if (APPEND_ONLY.has(config.name)) notes.push("APPEND-ONLY");
  const uniques = config.indexes
    .filter((index) => index.config.unique)
    .map((index) => {
      const cols = index.config.columns.map((c) =>
        "name" in c && typeof c.name === "string" ? c.name : "expr",
      );
      return `(${cols.join(", ")})${index.config.where ? " partial" : ""}`;
    });
  for (const constraint of config.uniqueConstraints)
    uniques.push(`(${constraint.columns.map((c) => c.name).join(", ")})`);

  const head = notes.length ? `**${config.name}** [${notes.join("; ")}]` : `**${config.name}**`;
  const tail = uniques.length ? ` — unique ${uniques.join(", ")}` : "";
  return `- ${head}: ${columns.join(", ")}${tail}`;
}

export function buildSchemaDoc(): string {
  const lines: string[] = [
    "# Database schema reference",
    "",
    "Generated from `src/server/db/schema/*.ts` by `pnpm exec tsx scripts/schema-doc.ts`. Do not edit by hand:",
    "`tests/unit/db/schema-doc.test.ts` fails when this file is out of date.",
    "",
    "## How to read it",
    "",
    "- One line per table: `column type`, in column order. `?` after a type means the column is nullable. `pk` is the primary key.",
    "- `→table cascade` is a foreign key to `table.id` and what happens when that row is deleted (`cascade`, `set null`, `restrict`).",
    "- Import tables from `@/server/db` by the camelCase form of the table name (`learner_profile` → `learnerProfile`), and columns likewise (`birth_month` → `birthMonth`). Exceptions are marked `export …`.",
    "- Every table has `id uuid` generated by the database. Times are `timestamptz`, stored in UTC and shown in Europe/London. Money is integer pence; `*_millipence` columns are thousandths of a penny.",
    "- `learner_id` always means `user.id` of a user whose `kind` is `learner`.",
    "- APPEND-ONLY tables refuse UPDATE, DELETE and TRUNCATE (database trigger). Their ids are deliberately not foreign keys. Only `withAppendOnlyMaintenance()` may delete from them, for retention.",
    "- Other database guards (see `drizzle/0001_append_only_and_guards.sql`): a `session` can never outlive `absolute_expires_at` or gain `two_factor_verified` after it is created; a `course_version` is frozen once `published_at` is set.",
    "- `user.email` is never null: learners hold a `<uuid>@learner.invalid` placeholder. Read it only through `userEmail()` in `@/server/auth/learner-email`.",
    "",
  ];

  let tableCount = 0;
  for (const { file, title, module } of FILES) {
    // Sorted by table name: the order of a module's exports differs between bundlers.
    const tables = Object.entries(module)
      .filter((entry): entry is [string, PgTable] => is(entry[1], PgTable))
      .sort((x, y) => getTableName(x[1]).localeCompare(getTableName(y[1]), "en"));
    tableCount += tables.length;
    lines.push(`## ${title} — \`${file}\` (${tables.length} tables)`, "");
    for (const [exportName, table] of tables) lines.push(describeTable(exportName, table));
    lines.push("");
  }

  lines.push("## Enums — `enums.ts`", "");
  lines.push(
    "Closed sets are Postgres enums. Open sets are `text`: `user.kind`, consent keys, notification types, feature-flag rules, AI feature keys and Stripe's subscription status.",
    "",
  );
  const enumEntries = Object.values(enums as Record<string, unknown>).filter(
    (value): value is PgEnum<[string, ...string[]]> => isPgEnum(value),
  );
  enumEntries.sort((x, y) => x.enumName.localeCompare(y.enumName, "en"));
  for (const pgEnum of enumEntries) {
    lines.push(`- **${pgEnum.enumName}**: ${pgEnum.enumValues.join(" | ")}`);
  }
  lines.push("", `${tableCount} tables, ${enumEntries.length} enums.`, "");
  return lines.join("\n");
}
