import { chromium } from "@playwright/test";
const BASE = "http://localhost:3211";
const fx = JSON.parse(process.argv[2]);
const year = new Date().getFullYear();
const browser = await chromium.launch({ channel: "chrome" });
const mobile = await browser.newContext({ baseURL: BASE, viewport: { width: 380, height: 800 } });
const desk = await browser.newContext({ baseURL: BASE, viewport: { width: 1280, height: 900 } });
let p = await mobile.newPage();
await p.goto("/signin"); await p.screenshot({ path: "/tmp/shot-signin-m.png", fullPage: true });
await p.goto("/signup/teen");
await p.getByLabel("Month").selectOption("3"); await p.getByLabel("Year").selectOption(String(year - 15));
await p.getByRole("button", { name: "Continue" }).click(); await p.getByLabel("Username").waitFor();
await p.screenshot({ path: "/tmp/shot-teen2-m.png", fullPage: true });
p = await desk.newPage();
await p.goto("/signin?as=parent");
const form = p.getByRole("form", { name: "Parent or carer sign-in" });
await form.getByLabel("Email address").fill(fx.parentEmail); await form.getByLabel("Password").fill(fx.password);
await form.getByRole("button", { name: "Sign in" }).click(); await p.waitForURL("**/parent");
await p.goto("/parent/onboarding"); await p.screenshot({ path: "/tmp/shot-ponb-d.png", fullPage: true });
await p.goto(`/parent/children/${fx.heldId}/consent`); await p.screenshot({ path: "/tmp/shot-consent-d.png", fullPage: true });
await p.goto("/parent/children/new"); await p.screenshot({ path: "/tmp/shot-addchild-d.png", fullPage: true });
const m2 = await browser.newContext({ baseURL: BASE, viewport: { width: 380, height: 800 } });
p = await m2.newPage();
await p.goto("/signin"); await p.getByLabel("Username").fill(fx.activeUsername); await p.getByLabel("Password").fill(fx.password);
await p.getByRole("button", { name: "Sign in" }).click(); await p.waitForURL("**/onboarding");
await p.screenshot({ path: "/tmp/shot-onb1-m.png", fullPage: true });
for (const tag of ["Music", "Games", "Coding"]) await p.getByLabel(tag, { exact: true }).check();
await p.getByRole("button", { name: "Continue" }).click(); await p.waitForURL("**/onboarding?step=avatar");
await p.screenshot({ path: "/tmp/shot-onb2-m.png", fullPage: true });
await browser.close();
